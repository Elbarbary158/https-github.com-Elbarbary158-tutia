// Helper to build realistic SVG receipt representations for instant zero-lag previews
export function generateReceiptSvg(
  merchant: string,
  ref: string,
  date: string,
  amountStr: string,
  items: { name: string; price: string }[],
  taxStr: string,
  totalStr: string
): string {
  const itemsSvg = items
    .map(
      (item, idx) => `
    <text x="24" y="${170 + idx * 24}" font-family="monospace" font-size="12" fill="#334155">${item.name}</text>
    <text x="336" y="${170 + idx * 24}" font-family="monospace" font-size="12" text-anchor="end" fill="#0f172a">${item.price}</text>`
    )
    .join('');

  const svgContent = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 360 480" width="100%" height="100%">
    <defs>
      <filter id="paper-shadow" x="-5%" y="-5%" width="110%" height="110%">
        <feDropShadow dx="0" dy="4" stdDeviation="6" flood-opacity="0.15" />
      </filter>
    </defs>
    <rect x="8" y="8" width="344" height="464" rx="6" fill="#ffffff" stroke="#cbd5e1" stroke-width="1.5" filter="url(#paper-shadow)" />
    <!-- Receipt Header -->
    <rect x="8" y="8" width="344" height="60" rx="6" fill="#0f172a" />
    <text x="180" y="36" font-family="sans-serif" font-weight="bold" font-size="15" text-anchor="middle" fill="#f8fafc">${merchant.toUpperCase()}</text>
    <text x="180" y="54" font-family="monospace" font-size="10" text-anchor="middle" fill="#94a3b8">OFFICIAL TAX INVOICE & RECEIPT</text>
    
    <!-- Meta details -->
    <text x="24" y="90" font-family="monospace" font-size="11" fill="#64748b">REF: ${ref}</text>
    <text x="336" y="90" font-family="monospace" font-size="11" text-anchor="end" fill="#64748b">DATE: ${date}</text>
    <line x1="24" y1="104" x2="336" y2="104" stroke="#e2e8f0" stroke-dasharray="4,4" stroke-width="1.5" />
    
    <!-- Header columns -->
    <text x="24" y="130" font-family="sans-serif" font-weight="bold" font-size="11" fill="#475569">DESCRIPTION</text>
    <text x="336" y="130" font-family="sans-serif" font-weight="bold" font-size="11" text-anchor="end" fill="#475569">AMOUNT</text>
    <line x1="24" y1="142" x2="336" y2="142" stroke="#cbd5e1" stroke-width="1" />
    
    <!-- Item rows -->
    ${itemsSvg}
    
    <!-- Totals separator -->
    <line x1="24" y1="340" x2="336" y2="340" stroke="#94a3b8" stroke-dasharray="2,2" stroke-width="1" />
    <text x="24" y="364" font-family="sans-serif" font-size="12" fill="#64748b">Subtotal</text>
    <text x="336" y="364" font-family="monospace" font-size="12" text-anchor="end" fill="#334155">${amountStr}</text>
    
    <text x="24" y="388" font-family="sans-serif" font-size="12" fill="#64748b">Tax / VAT (15%)</text>
    <text x="336" y="388" font-family="monospace" font-size="12" text-anchor="end" fill="#334155">${taxStr}</text>
    
    <rect x="20" y="404" width="320" height="36" rx="4" fill="#f1f5f9" />
    <text x="32" y="427" font-family="sans-serif" font-weight="bold" font-size="14" fill="#0f172a">TOTAL DUE / PAID</text>
    <text x="328" y="427" font-family="monospace" font-weight="bold" font-size="15" text-anchor="end" fill="#0284c7">${totalStr}</text>
    
    <!-- Barcode mock -->
    <text x="180" y="460" font-family="monospace" font-size="9" text-anchor="middle" fill="#94a3b8">*** AUTHORIZED AUDIT COPY ***</text>
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svgContent)}`;
}

